#!/usr/bin/env node
/**
 * Generates the feature registry from the directories under `features/`.
 *
 * Why this exists
 * ---------------
 * Contributors add a tool by creating `features/<slug>/` and nothing else.
 * The two files written here are gitignored and regenerated on predev,
 * prebuild, pretest and postinstall, so dozens of feature branches can be
 * open at once without a single shared file ever conflicting.
 */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const featuresDir = path.join(root, "features");
const outputDir = path.join(root, "core", "registry");
export const REGISTRY_SCHEMA_VERSION = 1;

const BANNER = `// AUTO-GENERATED by scripts/generate-registry.mjs — do not edit, do not commit.
// Run \`npm run registry\` to refresh.
`;

function identifier(slug) {
  return slug.replace(/[^a-zA-Z0-9]+(.)?/g, (_, chr) => (chr ? chr.toUpperCase() : ""));
}

async function discoverSlugs() {
  if (!existsSync(featuresDir)) return [];

  const dirents = await readdir(featuresDir, { withFileTypes: true });
  const slugs = [];

  for (const dirent of dirents) {
    if (!dirent.isDirectory() || dirent.name.startsWith(".") || dirent.name.startsWith("_")) {
      continue;
    }

    const manifestPath = path.join(featuresDir, dirent.name, "manifest.ts");
    const panelPath = path.join(featuresDir, dirent.name, "panel.tsx");

    if (!existsSync(manifestPath)) {
      console.warn(`[registry] skipping ${dirent.name}: manifest.ts is missing`);
      continue;
    }
    if (!existsSync(panelPath)) {
      console.warn(`[registry] skipping ${dirent.name}: panel.tsx is missing`);
      continue;
    }

    const manifestSource = await readFile(manifestPath, "utf8");
    const declared = manifestSource.match(/slug:\s*"([^"]+)"/)?.[1];
    if (declared && declared !== dirent.name) {
      throw new Error(
        `[registry] features/${dirent.name}/manifest.ts declares slug "${declared}". ` +
          "The slug must match the directory name."
      );
    }

    slugs.push(dirent.name);
  }

  return slugs.sort();
}

export function renderManifests(slugs, schemaVersion = REGISTRY_SCHEMA_VERSION) {
  const imports = slugs
    .map((slug) => `import { manifest as ${identifier(slug)} } from "@/features/${slug}/manifest";`)
    .join("\n");

  const entries = slugs.map((slug) => `  ${identifier(slug)}`).join(",\n");

  return `${BANNER}
import type { FeatureManifest } from "@/core/registry/types";
${imports}

export const generatedRegistrySchemaVersion = ${schemaVersion} as const;
export const generatedManifests: FeatureManifest[] = [
${entries}
];
`;
}

export function renderPanels(slugs, schemaVersion = REGISTRY_SCHEMA_VERSION) {
  const imports = slugs
    .map(
      (slug) =>
        `const ${identifier(slug)}Panel = dynamic(() => import("@/features/${slug}/panel"));`
    )
    .join("\n");

  const entries = slugs
    .map((slug) => `  "${slug}": ${identifier(slug)}Panel`)
    .join(",\n");

  return `${BANNER}
import dynamic from "next/dynamic";
import type { ComponentType } from "react";

${imports}

export const generatedRegistrySchemaVersion = ${schemaVersion} as const;
export const generatedPanels: Record<string, ComponentType> = {
${entries}
};
`;
}

export function renderRegistry(slugs, schemaVersion = REGISTRY_SCHEMA_VERSION) {
  const imports = slugs
    .map((slug) => `import { manifest as ${identifier(slug)} } from "@/features/${slug}/manifest";`)
    .join("\n");

  const panelImports = slugs
    .map((slug) => `import ${identifier(slug)}Panel from "@/features/${slug}/panel";`)
    .join("\n");

  const entries = slugs
    .map(
      (slug) =>
        `  { manifest: ${identifier(slug)}, Panel: ${identifier(slug)}Panel }`
    )
    .join(",\n");

  return `${BANNER}
import type { FeatureEntry } from "@/core/registry/types";
${imports}
${panelImports}

export const generatedRegistrySchemaVersion = ${schemaVersion} as const;
export const generatedFeatures: FeatureEntry[] = [
${entries}
];
`;
}

async function main() {
  const slugs = await discoverSlugs();
  await mkdir(outputDir, { recursive: true });

  await writeFile(path.join(outputDir, "registry.generated.ts"), renderRegistry(slugs), "utf8");
  await writeFile(path.join(outputDir, "manifests.generated.ts"), renderManifests(slugs), "utf8");
  await writeFile(path.join(outputDir, "panels.generated.ts"), renderPanels(slugs), "utf8");

  console.log(`[registry] ${slugs.length} feature slice(s) registered`);
  for (const slug of slugs) console.log(`  - ${slug}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
