#!/usr/bin/env node
/**
 * Generates the feature registry from the directories under `features/`.
 *
 * Why this exists
 * ---------------
 * Contributors add a tool by creating `features/<slug>/` and nothing else.
 * The registry manifests and panels are generated deterministically and tracked
 * in git so local and CI environments agree without configuration drift.
 */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const featuresDir = path.join(root, "features");
const outputDir = path.join(root, "core", "registry");
export const REGISTRY_SCHEMA_VERSION = 1;

const BANNER = `// AUTO-GENERATED by scripts/generate-registry.mjs — do not edit directly.
// Run \`npm run registry\` to refresh.
`;

const REQUIRED_MANIFEST_FIELDS = [
  "slug",
  "title",
  "description",
  "character",
  "category",
  "status",
  "icon",
  "networks",
  "keywords"
];

// Mirrors FeatureStatus in core/registry/types.ts. Duplicated rather than
// imported because this script runs directly under node with no build step.
const ALLOWED_STATUSES = ["working", "beta", "experimental"];

// Mirrors STELLAR_NETWORKS in core/network/types.ts.
const ALLOWED_NETWORKS = ["testnet", "mainnet"];

/**
 * Schemes a manifest must never carry. `http:` is included because an
 * insecure link in navigation is a downgrade the author did not choose, and
 * the script schemes are the ones that execute when a link is followed.
 */
const FORBIDDEN_LINK_SCHEMES = ["http:", "javascript:", "data:", "vbscript:", "file:"];

function fieldError(slug, field, reason) {
  return new Error(`[registry] features/${slug}/manifest.ts ${field}: ${reason}`);
}

function stringArrayField(source, field) {
  const body = source.match(new RegExp(`${field}:\\s*\\[([^\\]]*)\\]`, "m"))?.[1];
  if (body === undefined) return null;
  return [...body.matchAll(/"([^"]*)"/g)].map((match) => match[1]);
}

/**
 * Validate the *values* in a manifest, not just that the fields are present.
 *
 * Manifest metadata reaches navigation, search, the command palette and page
 * headings, so a malformed entry has a wider blast radius than a single tool.
 * A missing field throws on its own; a wrong value used to be written straight
 * through into the generated registry and only failed later, somewhere else.
 *
 * Each rejection names the slice and the field, so the error points at the line
 * to fix rather than at "the registry".
 */
export function validateManifestMetadata(slug, source) {
  // status
  const status = source.match(/status:\s*"([^"]*)"/)?.[1];
  if (status !== undefined && !ALLOWED_STATUSES.includes(status)) {
    throw fieldError(
      slug,
      "status",
      `"${status}" is not a valid feature status. Expected one of: ${ALLOWED_STATUSES.join(", ")}.`
    );
  }

  // networks
  const networks = stringArrayField(source, "networks");
  if (networks) {
    for (const network of networks) {
      if (!ALLOWED_NETWORKS.includes(network)) {
        throw fieldError(
          slug,
          "networks",
          `"${network}" is not a supported Stellar network. Expected one of: ${ALLOWED_NETWORKS.join(", ")}, or an empty array for an offline tool.`
        );
      }
    }
  }

  // keywords
  const keywords = stringArrayField(source, "keywords");
  if (keywords) {
    const seen = new Map();
    for (const keyword of keywords) {
      const normalized = keyword.trim().toLowerCase();
      if (seen.has(normalized)) {
        throw fieldError(
          slug,
          "keywords",
          `duplicate keyword "${keyword}" (also declared as "${seen.get(normalized)}"). Keywords are used for search filtering, so a duplicate adds nothing.`
        );
      }
      seen.set(normalized, keyword);
    }
  }

  // external links
  for (const literal of source.matchAll(/"([^"]*)"|'([^']*)'/g)) {
    const value = literal[1] ?? literal[2] ?? "";
    const scheme = value.match(/^([a-z][a-z0-9+.-]*:)/i)?.[1]?.toLowerCase();
    if (scheme && FORBIDDEN_LINK_SCHEMES.includes(scheme)) {
      throw fieldError(
        slug,
        "link",
        `"${value}" uses the forbidden scheme "${scheme}". Use https:// for external links.`
      );
    }
  }

  return true;
}

function identifier(slug) {
  return slug.replace(/[^a-zA-Z0-9]+(.)?/g, (_, chr) => (chr ? chr.toUpperCase() : ""));
}

function assertManifestFields(slug, source) {
  const missing = REQUIRED_MANIFEST_FIELDS.filter((field) => !new RegExp(`${field}:`, "m").test(source));
  if (missing.length > 0) {
    throw new Error(
      `[registry] features/${slug}/manifest.ts is missing required field(s): ${missing.join(", ")}`
    );
  }
}

async function walk(dir, prefix = "") {
  const out = [];
  const dirents = await readdir(dir, { withFileTypes: true });

  for (const dirent of dirents) {
    const relative = prefix ? `${prefix}/${dirent.name}` : dirent.name;
    if (dirent.isDirectory()) {
      out.push(...(await walk(path.join(dir, dirent.name), relative)));
      continue;
    }
    out.push(relative);
  }

  return out;
}

async function validateFeatureDirectory(slug) {
  const featureDir = path.join(featuresDir, slug);
  const manifestPath = path.join(featureDir, "manifest.ts");
  const panelPath = path.join(featureDir, "panel.tsx");

  if (!existsSync(manifestPath)) {
    throw new Error(`[registry] features/${slug}/manifest.ts is missing`);
  }
  if (!existsSync(panelPath)) {
    throw new Error(`[registry] features/${slug}/panel.tsx is missing`);
  }

  const source = await readFile(manifestPath, "utf8");
  const declared = source.match(/slug:\s*"([^"]+)"/)?.[1];
  if (declared && declared !== slug) {
    throw new Error(
      `[registry] features/${slug}/manifest.ts declares slug "${declared}". ` +
        "The slug must match the directory name."
    );
  }

  const files = await walk(featureDir);
  for (const relative of files) {
    const normalized = relative.replaceAll("\\", "/");
    if (!/\.(ts|tsx)$/.test(normalized)) continue;
    if (
      normalized.startsWith("__tests__/") ||
      normalized.includes("/__tests__/") ||
      normalized.startsWith("fixtures/") ||
      normalized.includes("/fixtures/") ||
      normalized.startsWith("msw/") ||
      normalized.includes("/msw/") ||
      normalized.startsWith("e2e/") ||
      normalized.includes("/e2e/")
    ) {
      continue;
    }

    const filePath = path.join(featureDir, relative);
    const fileText = await readFile(filePath, "utf8");
    const imports = [...fileText.matchAll(/(?:import|export)\s+(?:[^'\"]+\s+from\s+)?["']([^"']+)["']/g)]
      .map((match) => match[1])
      .filter((value) => value.startsWith("@/features/"));

    for (const imported of imports) {
      const target = imported.replace(/^@\/features\//, "");
      const targetSlug = target.split("/")[0];
      if (targetSlug !== slug && targetSlug !== "core") {
        throw new Error(
          `[registry] features/${slug} imports another feature's internals: ${imported}. ` +
            "Slices may only import from @/core or their own feature directory."
        );
      }
    }
  }

  assertManifestFields(slug, source);
  validateManifestMetadata(slug, source);
}

export async function discoverSlugs() {
  if (!existsSync(featuresDir)) return [];

  const dirents = await readdir(featuresDir, { withFileTypes: true });
  const slugs = [];
  const seen = new Map();

  for (const dirent of dirents) {
    if (!dirent.isDirectory() || dirent.name.startsWith(".") || dirent.name.startsWith("_")) {
      continue;
    }

    await validateFeatureDirectory(dirent.name);

    const manifestSource = await readFile(path.join(featuresDir, dirent.name, "manifest.ts"), "utf8");
    const declared = manifestSource.match(/slug:\s*"([^"]+)"/)?.[1];
    if (declared) {
      if (seen.has(declared)) {
        throw new Error(
          `[registry] duplicate feature slug "${declared}" found in ${seen.get(declared)} and ${dirent.name}`
        );
      }
      seen.set(declared, dirent.name);
    }

    slugs.push(dirent.name);
  }

  return slugs.sort();
}

export function renderManifests(slugs, schemaVersion = REGISTRY_SCHEMA_VERSION) {
  const imports = slugs
    .map((slug) => `import { manifest as ${identifier(slug)} } from "@/features/${slug}/manifest";`)
    .join("\n");

  const entries = slugs.map((slug) => `  ${identifier(slug)}`).join(",\n");

  return `${BANNER}
import type { FeatureManifest } from "@/core/registry/types";
${imports}

export const generatedRegistrySchemaVersion = ${schemaVersion} as const;
export const generatedManifests: FeatureManifest[] = [
${entries}
];
`;
}

export function renderPanels(slugs, schemaVersion = REGISTRY_SCHEMA_VERSION) {
  const entries = slugs
    .map(
      (slug) =>
        `  "${slug}": () => import("@/features/${slug}/panel").then((mod) => mod.default as ComponentType)`
    )
    .join(",\n");

  return `${BANNER}
import type { ComponentType } from "react";

export const generatedRegistrySchemaVersion = ${schemaVersion} as const;
export const generatedPanels: Record<string, ComponentType> = {
${entries}
};
`;
}

export function renderRegistry(slugs, schemaVersion = REGISTRY_SCHEMA_VERSION) {
  const imports = slugs
    .map((slug) => `import { manifest as ${identifier(slug)} } from "@/features/${slug}/manifest";`)
    .join("\n");

  const entries = slugs
    .map(
      (slug) =>
        `  { manifest: ${identifier(slug)}, load: async () => { const mod = await import("@/features/${slug}/panel"); return mod.default as ComponentType; } }`
    )
    .join(",\n");

  return `${BANNER}
import type { ComponentType } from "react";
import type { FeatureEntry } from "@/core/registry/types";
${imports}

export const generatedRegistrySchemaVersion = ${schemaVersion} as const;
export const generatedFeatures: FeatureEntry[] = [
${entries}
];
`;
}

export async function generateRegistry({ check = false } = {}) {
  const slugs = await discoverSlugs();
  await mkdir(outputDir, { recursive: true });

  const nextRegistry = renderRegistry(slugs);
  const nextManifests = renderManifests(slugs);
  const nextPanels = renderPanels(slugs);

  const targets = [
    { filename: "registry.generated.ts", content: nextRegistry },
    { filename: "manifests.generated.ts", content: nextManifests },
    { filename: "panels.generated.ts", content: nextPanels }
  ];

  if (check) {
    let hasDiff = false;
    for (const target of targets) {
      const fullPath = path.join(outputDir, target.filename);
      const existing = existsSync(fullPath) ? await readFile(fullPath, "utf8") : "";
      if (existing !== target.content) {
        hasDiff = true;
        console.error(`[registry] Stale or uncommitted generated file: core/registry/${target.filename}`);
      }
    }

    if (hasDiff) {
      console.error("\n[registry] -------------------------------------------------------------");
      console.error("[registry] Stale generated registry files detected!");
      console.error("[registry] The committed core/registry/*.generated.ts do not match features/.");
      console.error("[registry] Actionable fix for contributor:");
      console.error("[registry]   1. Run `npm run registry` to regenerate the registry files.");
      console.error("[registry]   2. Review the diff: `git diff core/registry/`");
      console.error("[registry]   3. Commit the updated files: `git add core/registry/*.generated.ts`");
      console.error("[registry] -------------------------------------------------------------\n");
      throw new Error("Registry is out of date. Run `npm run registry` and commit the updated files.");
    }

    console.log(`[registry] OK: all ${slugs.length} feature slices are deterministically registered and up to date.`);
    return { slugs, changed: false };
  }

  for (const target of targets) {
    await writeFile(path.join(outputDir, target.filename), target.content, "utf8");
  }

  console.log(`[registry] ${slugs.length} feature slice(s) registered`);
  for (const slug of slugs) console.log(`  - ${slug}`);
  return { slugs, changed: true };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const isCheck = process.argv.includes("--check") || process.argv.includes("--verify");
  generateRegistry({ check: isCheck }).catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
